def live_sources(board_map: BoardMap) -> List[Source]:
    """The boards to scrape: every `live` board of every company."""
    return [
        board.source
        for company in board_map.companies
        for board in company.boards
        if board.status == "live"
    ]


def is_due(
    company: Optional[CompanyEntry], now: datetime, recheck_days: int
) -> bool:
    """Does this company need checking? True when it is not in the map yet, is
    flagged `needs_check`, was never checked, or was last checked more than
    `recheck_days` ago. The one place that rule lives (how often to recheck is a
    decision for the later maintenance cycle)."""
    if company is None or company.needs_check or not company.checked_at:
        return True
    try:
        checked = _naive_utc(datetime.fromisoformat(company.checked_at))
    except ValueError:
        return True  # an unreadable time is as good as never checked
    return _naive_utc(now) - checked > timedelta(days=recheck_days)


def drop_missing_companies(board_map: BoardMap, names: List[str]) -> BoardMap:
    """The map without entries for companies no longer listed in companies.txt."""
    wanted = {name.strip().lower() for name in names}
    return BoardMap(
        companies=[
            copy.deepcopy(c) for c in board_map.companies if c.name.lower() in wanted
        ]
    )


def merge_check(
    board_map: BoardMap, company: str, results: List[CheckResult], now: datetime
) -> BoardMap:
    """The map after checking `company`'s candidate boards (the input is not
    changed).

    - a live board with postings is `live`; live with none is `empty`;
    - a board already in the map that is now dead becomes `gone`, and one that
      is already `gone` stays so;
    - a dead board that was never in the map is not recorded;
    - an inconclusive failure (see `CheckResult`) changes nothing for that board;
    - the company's `needs_check` is cleared and `checked_at` set.
    """
    updated = copy.deepcopy(board_map)
    stamp = format_time(now)
    entry = updated.find_company(company)
    if entry is None:
        entry = CompanyEntry(name=company)
        updated.companies.append(entry)

    for result in results:
        board = entry.find_board(result.source)
        if result.live:
            status: Status = "live" if result.postings > 0 else "empty"
            if board is None:
                board = BoardEntry(
                    line=source_to_line(result.source), status=status, first_seen=stamp
                )
                entry.boards.append(board)
            board.status = status
            board.postings = result.postings
            board.matched = result.matched
            if status == "live":
                board.last_live = stamp
                board.misses = 0
                board.last_miss_on = None
        elif board is not None and not result.inconclusive:
            board.status = "gone"
            board.postings = 0
            board.matched = 0

    entry.needs_check = False
    entry.checked_at = stamp
    return updated


def is_definite_miss(outcome: Outcome) -> bool:
    """Does this scrape outcome say the board is not there?

    Definite: a scrape that returned no postings, or an HTTP 404, 410 or 422
    (`http_util` re-raises a 4xx at once, with its response attached).
    Everything else says nothing about whether the board exists: a timeout, a
    connection error, a 5xx (after the retries), a scraper's own error such as
    `WorkdayError` (a capped or inconsistent list), and a scrape that returned
    postings.
    """
    if isinstance(outcome, BaseException):
        if isinstance(outcome, requests.HTTPError):
            status = getattr(outcome.response, "status_code", None)
            return status in DEFINITE_MISS_STATUSES
        return False
    return outcome == 0


def apply_scrape_outcomes(
    board_map: BoardMap,
    outcomes: List[Tuple[BoardKey, Outcome]],
    stale_after: int,
    now: datetime,
    pinned: Collection[BoardKey] = (),
) -> Tuple[BoardMap, List[Source]]:
    """The map after a scrape, and the boards whose stored rows to retire (the
    input is not changed).

    For each mapped (`live`) board that was scraped:
    - postings returned: `misses` back to 0, `last_miss_on` cleared, `last_live`
      and `postings` updated;
    - a definite miss (`is_definite_miss`): `misses` goes up by one, at most once
      per board per calendar day (UTC), so `stale_after` means that many
      separate days. At `stale_after` the board becomes `gone` and its company is
      flagged `needs_check`, so the next `make resolve` looks for it elsewhere;
    - anything else is not a miss: the counters are left alone.

    Pinned boards (`pinned`, as `source_key()` values) are never touched: they
    are your explicit choice, and a failing one is only logged by the scrape.
    """
    updated = copy.deepcopy(board_map)
    stamp = format_time(now)
    today = _naive_utc(now).date().isoformat()
    retire: List[Source] = []
    retired_keys = set()

    for (kind, token), outcome in outcomes:
        key = (kind, token.strip().lower())
        if key in pinned:
            continue
        for company in updated.companies:
            for board in company.boards:
                if board.status != "live" or source_key(board.source) != key:
                    continue
                if not isinstance(outcome, BaseException) and outcome > 0:
                    board.misses = 0
                    board.last_miss_on = None
                    board.last_live = stamp
                    board.postings = outcome
                elif is_definite_miss(outcome):
                    if board.last_miss_on != today:
                        board.misses += 1
                        board.last_miss_on = today
                    if board.misses >= stale_after:
                        board.status = "gone"
                        board.postings = 0
                        board.matched = 0
                        company.needs_check = True
                        if key not in retired_keys:
                            retired_keys.add(key)
                            retire.append(board.source)
    return updated, retire
